import JSZip from 'jszip';
import { toast } from 'sonner';

export interface ProjectFile {
  name: string;
  path: string;
  content: string;
}

export interface ReadyProjectBundle {
  id: string;
  title: string;
  type: 'roblox' | 'minecraft' | 'webapp' | 'godot' | 'unity' | 'generic';
  description: string;
  files: ProjectFile[];
}

export const zipProjectService = {
  /**
   * Bundles any collection of files into a production-grade ready-to-open .zip archive
   * and triggers an immediate download in the browser.
   */
  async downloadReadyToOpenZip(bundle: ReadyProjectBundle): Promise<void> {
    try {
      const zip = new JSZip();

      // Add each file in its proper nested folder structure
      bundle.files.forEach((file) => {
        const cleanPath = file.path.startsWith('/') ? file.path.slice(1) : file.path;
        zip.file(cleanPath, file.content);
      });

      // Include a standard manifest / quickstart README if not already present
      if (!bundle.files.some((f) => f.path.toLowerCase().endsWith('readme.md'))) {
        zip.file(
          'README.md',
          `# ${bundle.title}\n\nGenerated by Flash AI Assistant.\nType: ${bundle.type}\n\n## Quick Start:\n1. Unzip this folder into your project directory.\n2. Open with your preferred IDE, Roblox Studio, or Minecraft datapacks directory.\n`
        );
      }

      // Generate the zip blob
      const blob = await zip.generateAsync({
        type: 'blob',
        compression: 'DEFLATE',
        compressionOptions: { level: 6 },
      });

      // Trigger instant browser download
      const safeName = bundle.title.toLowerCase().replace(/[^a-z0-9]/g, '_');
      const filename = `${safeName}_project.zip`;
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);

      toast.success(`🎉 Downloaded ready-to-open project archive: ${filename}`);
    } catch (err) {
      console.error('Error generating project ZIP:', err);
      toast.error('Failed to create project ZIP archive. Please try again.');
    }
  },

  /**
   * Parses markdown code blocks from an AI response and converts them
   * into an immediate ready-to-open multi-file project bundle.
   */
  createBundleFromAiContent(
    title: string,
    content: string,
    fallbackType: ReadyProjectBundle['type'] = 'webapp'
  ): ReadyProjectBundle {
    const files: ProjectFile[] = [];
    const codeBlockRegex = /```([a-zA-Z0-9_\-+]*)\s*(?:\/\/\s*filename:\s*([^\n\r]+)|\/\*\s*filename:\s*([^\n\r*]+)\*\/|#\s*filename:\s*([^\n\r]+)|--\s*filename:\s*([^\n\r]+))?\n([\s\S]*?)```/g;

    let match;
    let fileIndex = 1;

    while ((match = codeBlockRegex.exec(content)) !== null) {
      const lang = match[1] || 'text';
      const explicitName = (match[2] || match[3] || match[4] || match[5] || '').trim();
      const code = match[6];

      let fileName = explicitName;
      if (!fileName) {
        if (lang === 'typescript' || lang === 'tsx') fileName = `src/Component_${fileIndex}.tsx`;
        else if (lang === 'javascript' || lang === 'jsx') fileName = `src/script_${fileIndex}.js`;
        else if (lang === 'lua' || lang === 'luau') fileName = `src/ServerScript_${fileIndex}.luau`;
        else if (lang === 'html') fileName = `index_${fileIndex}.html`;
        else if (lang === 'css') fileName = `styles_${fileIndex}.css`;
        else if (lang === 'python') fileName = `main_${fileIndex}.py`;
        else if (lang === 'mcfunction') fileName = `data/custom/functions/func_${fileIndex}.mcfunction`;
        else fileName = `file_${fileIndex}.${lang || 'txt'}`;
      }

      files.push({
        name: fileName.split('/').pop() || fileName,
        path: fileName,
        content: code,
      });
      fileIndex++;
    }

    // If no explicit code blocks were parsed, wrap the entire content into a file
    if (files.length === 0) {
      files.push({
        name: 'solution.txt',
        path: 'solution.txt',
        content,
      });
    }

    return {
      id: `proj_${Date.now()}`,
      title,
      type: fallbackType,
      description: `Project generated from AI code output with ${files.length} files`,
      files,
    };
  },
};
